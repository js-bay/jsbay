//! Engine-level bytecode cache.
//!
//! One call compiles a script to QuickJS bytecode, persists it under `cache_dir`, and re-executes the cached bytes on later launches — skipping the parse step entirely. The cache key is derived from source SHA-256, a caller version salt, and a library-generated build fingerprint.
//!
//! Degradation contract: any failure (missing dir, corrupt bytes, version or fingerprint change, JNI/alloc issue) falls back to a plain evalScript, so enabling the cache can never break cold start.
//!
//! Safety: like every other engine API, operations on a given instance_id MUST happen on the owning thread. File I/O here is synchronous; for on-device cold-start paths that is the desired cost (compile is far more expensive than the read we save).
//!
//! Trust boundary: `cache_dir` must be an application-private directory (e.g. Android cacheDir / iOS caches), never a world-writable path. A cache file is content-addressed by the source hash, but an attacker who can write the directory could replace a victim's `<version>-<hash>.bc` with arbitrary executable bytecode keyed the same way. Placing the root under app-scoped storage is the caller's responsibility.

const std = @import("std");
const io = @import("../platform/io.zig");
const bytecode_cache = @import("bytecode_cache");
const build_options = @import("build_options");
const engine = @import("../engine.zig");
const instance_map = @import("../runtime/instance_map.zig");
const bytecode = @import("bytecode.zig");
const types = @import("../types.zig");

/// Result of a cached evaluation — same shape as EvalResult but also reports whether the cached variant was used, for telemetry.
pub const CachedEvalResult = struct {
    result: ?[]const u8 = null,
    err: ?[]const u8 = null,
    err_is_heap: bool = false,
    /// True when a cache file existed and ran; false when we compiled fresh (or degraded to plain eval) or a runtime exception was re-surfaced from a cached run.
    cache_hit: bool = false,
};

pub fn sha256Hex(source: []const u8) []u8 {
    return bytecode_cache.sha256Hex(std.heap.c_allocator, source) orelse &.{};
}

const CACHE_NAME_KEY_BYTES = 32;

/// Build `<cache_dir>/<version>-<fingerprint>-<srckey>-<namekey>.bc`. `fingerprint` is generated by the library build and separates bytecode produced by incompatible engine builds or target ABIs. `namekey` is a full-length prefix of the filename hash, so two filenames cannot share an artifact whose compile-time filename would leak into later stack traces.
pub fn cachePathWithFingerprint(gpa: std.mem.Allocator, cache_dir: []const u8, version: []const u8, fingerprint: []const u8, srckey: []const u8, namekey: []const u8) ?[]u8 {
    return bytecode_cache.artifactPath(gpa, cache_dir, version, fingerprint, srckey, namekey);
}

/// Build a cache path using the fingerprint compiled into this library.
pub fn cachePath(gpa: std.mem.Allocator, cache_dir: []const u8, version: []const u8, srckey: []const u8, namekey: []const u8) ?[]u8 {
    return cachePathWithFingerprint(gpa, cache_dir, version, build_options.bytecode_fingerprint, srckey, namekey);
}

/// Version strings are spliced into cache file names, so they must be safe single path components. Reject anything that could traverse outside `cache_dir` (`../`, separators, embedded nulls, path metacharacters).
pub fn isSafeVersion(v: []const u8) bool {
    return bytecode_cache.isSafeComponent(v);
}

/// Evaluate `source` (a named engine-level script, e.g. an asset bundle) using the bytecode cache rooted at `cache_dir`.
///
/// The caller is responsible for only passing *deterministic* scripts here — same source must mean same script (a stable asset), since the key is purely content-derived. Ad-hoc session fragments (<eval> with embedded ids) must NOT go through this path: every instance would be a distinct cache entry that never hits, bloating the cache dir.
///
/// `version` is a user-supplied engine-version string; changing it invalidates every prior entry (mismatched bytecode streams would fail at run time and get rebuilt anyway, but the explicit version keeps the dir from accumulating stale garbage across engine upgrades).
pub fn evalCached(instance_id: i32, source: []const u8, filename: []const u8, cache_dir: []const u8, version: []const u8) CachedEvalResult {
    return evalCachedWithFingerprint(
        instance_id,
        source,
        filename,
        cache_dir,
        version,
        build_options.bytecode_fingerprint,
    );
}

/// Evaluate through a supplied build fingerprint. Production callers use `evalCached`; this variant keeps cache-identity behavior directly testable.
pub fn evalCachedWithFingerprint(instance_id: i32, source: []const u8, filename: []const u8, cache_dir: []const u8, version: []const u8, fingerprint: []const u8) CachedEvalResult {
    if (!build_options.bytecode_cache) return plainEval(instance_id, source, filename);
    // Small scripts are cheaper to parse than to read/deserialize back.
    if (source.len < 4 * 1024) return plainEval(instance_id, source, filename);
    if (!isSafeVersion(version) or !isSafeVersion(fingerprint) or cache_dir.len == 0) return plainEval(instance_id, source, filename);

    const gpa = std.heap.c_allocator;
    const srckey = sha256Hex(source);
    if (srckey.len == 0) return plainEval(instance_id, source, filename);
    defer gpa.free(srckey);
    const namekey = sha256Hex(filename);
    if (namekey.len == 0) return plainEval(instance_id, source, filename);
    defer gpa.free(namekey);

    const path = cachePathWithFingerprint(gpa, cache_dir, version, fingerprint, srckey, namekey) orelse
        return plainEval(instance_id, source, filename);
    defer gpa.free(path);

    // Attempt cache hit: read + run. If the bytes won't even decode (stale/version-bumped/corrupt), drop the artifact and rebuild once. If the *script* throws at runtime, that is not a cache problem: the exception is re-surfaced directly and the cache file is kept, so a side-effecting script is never executed twice.
    if (readBytes(path)) |cached| {
        defer gpa.free(cached);
        const res = bytecode.runBytecode(instance_id, cached);
        if (res.err == null) {
            return evalResultToCached(res, true);
        }
        if (instance_map.getInstance(instance_id) == null) {
            freeEvalResult(res);
            return .{ .err = engine.instance_not_found_err, .err_is_heap = false, .cache_hit = false };
        }
        const rebuildable = res.decode_failed;
        const err = res.err;
        const err_is_heap = res.err_is_heap;
        const result_str = res.result;
        if (rebuildable) {
            // Stale payload: free fully, remove, and recompile below.
            freeEvalResult(res);
            deleteFile(path);
        } else {
            // Runtime exception from the cached run: keep the cache, hand the exception through unchanged.
            if (result_str) |r| std.heap.c_allocator.free(@constCast(r));
            return .{ .result = null, .err = err, .err_is_heap = err_is_heap, .cache_hit = true };
        }
    }

    // Cache miss: compile now, persist, run.
    const compiled = bytecode.compile(instance_id, source, filename);
    defer bytecode.freeCompileResult(compiled);
    if (compiled.bytes) |bytes| {
        // Best-effort persist; a failure to write only means next launch recompiles, never that this launch fails.
        writeBytes(path, bytes);
        const res = bytecode.runBytecode(instance_id, bytes);
        return evalResultToCached(res, false);
    }

    // Compile failed (syntax error): surface it the way evalScript would.
    return plainEval(instance_id, source, filename);
}

fn plainEval(instance_id: i32, source: []const u8, filename: []const u8) CachedEvalResult {
    const res = engine.evalScript(instance_id, source, filename);
    return evalResultToCached(res, false);
}

fn evalResultToCached(res: types.EvalResult, hit: bool) CachedEvalResult {
    return .{
        .result = res.result,
        .err = res.err,
        .err_is_heap = res.err_is_heap,
        .cache_hit = hit,
    };
}

/// Free both the result string and any heap-allocated error string. The error, when `err_is_heap`, is c_allocator-owned and must be freed just like the result.
fn freeEvalResult(res: types.EvalResult) void {
    if (res.result) |r| std.heap.c_allocator.free(@constCast(r));
    if (res.err_is_heap) {
        if (res.err) |e| std.heap.c_allocator.free(@constCast(e));
    }
}

pub fn readBytes(path: []const u8) ?[]u8 {
    return bytecode_cache.read(io.get(), std.heap.c_allocator, path);
}

pub fn writeBytes(path: []const u8, bytes: []const u8) void {
    bytecode_cache.writeAtomically(io.get(), std.heap.c_allocator, path, bytes);
}

pub fn deleteFile(path: []const u8) void {
    bytecode_cache.delete(io.get(), path);
}
